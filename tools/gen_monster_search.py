import argparse
from pathlib import Path
import yaml
from gen_loot import rows, num, pretty, lua_str


def generate(root, output):
    sql = root / 'sql'
    species = {}
    eco = yaml.safe_load((root / 'data/ecosystems.yaml').read_text())
    for ecosystem in eco['ecosystems'].values():
        for family, info in ecosystem.get('families', {}).items():
            for spec in info.get('species', {}).values():
                species[spec['id']] = pretty(family)
    pools = {num(r[0]): (species.get(num(r[3]), 'Unclassified'), bool(num(r[14]) & 2))
             for r in rows(sql / 'mob_pools.sql', 'mob_pools')}
    groups = {(num(r[0]), num(r[2])): (num(r[1]), num(r[6]))
              for r in rows(sql / 'mob_groups.sql', 'mob_groups')}
    items = {num(r[0]): pretty(r[2]) for r in rows(sql / 'item_basic.sql', 'item_basic')}
    drops = {}
    for row in rows(sql / 'mob_droplist.sql', 'mob_droplist'):
        if num(row[5]) > 0 and num(row[4]) in items:
            drops.setdefault(num(row[0]), set()).add(items[num(row[4])])
    records = {}
    for r in rows(sql / 'mob_spawn_points.sql', 'mob_spawn_points'):
        zone = (num(r[0]) >> 12) & 0xfff
        group = groups.get((num(r[4]), zone))
        if not group or group[0] not in pools or num(r[5]) <= 0 or num(r[6]) < num(r[5]):
            continue
        family, nm = pools[group[0]]
        name = r[3] or pretty(r[2])
        key = name, zone
        rec = records.setdefault(key, dict(name=name, zone=zone, family=family, nm=nm,
            lo=num(r[5]), hi=num(r[6]), drops=set()))
        rec['lo'] = min(rec['lo'], num(r[5]))
        rec['hi'] = max(rec['hi'], num(r[6]))
        rec['drops'].update(drops.get(group[1], set()))
    result = ['-- Copyright (c) 2026 Daniel Bates / Bates LLC. All rights reserved.',
              '-- Generated by tools/gen_monster_search.py from public LandSandBoat data.',
              '-- Standard reference, not confirmation of any private server population.',
              'return {']
    for key, r in sorted(records.items()):
        fields = [f'name = {lua_str(r["name"])}', f'zone = {r["zone"]}',
                  f'family = {lua_str(r["family"])}', f'lo = {r["lo"]}', f'hi = {r["hi"]}',
                  f'nm = {str(r["nm"]).lower()}',
                  f'drops = {lua_str(", ".join(sorted(r["drops"])[:12]))}',
                  "source = 'https://github.com/LandSandBoat/server'", "scope = 'Standard reference'"]
        result.append('    { ' + ', '.join(fields) + ' },')
    result.append('}\n')
    output.write_text('\n'.join(result))
    print(f'{len(records)} monster/zone records written')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('root', type=Path)
    ap.add_argument('--output', type=Path, default=Path('Vanaguide/data/monster_search.lua'))
    args = ap.parse_args()
    generate(args.root, args.output)
