#!/usr/bin/env python3
"""Vanaguide :: tools/gen_quest_steps.py

Build data/quest_steps.lua: what to do, step by step, for every quest and mission.

The steps were written by reading each LandSandBoat quest/mission script (sections, trades,
key items, battlefields, waits, rewards, and the developers' own comments) and were checked
against those scripts by a second reader. This tool only validates and writes them:

    tools/gen_quest_steps.py tools/data/quest_steps.json --npcs <LSB>/sql/npc_list.sql

entries.json: [{kind: quest|mission, area, id, name, scripted: full|partial|stub, steps: [...]}]

Copyright (c) 2026 Bates LLC.  All rights reserved.
"""
import argparse
import json
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_quests import lua_str  # noqa: E402

HEADER = """-- Vanaguide :: data/quest_steps.lua
-- GENERATED by tools/gen_quest_steps.py from LandSandBoat's quest and mission scripts.  Do not hand-edit.
-- What to do for each quest and mission, in order. Read by VanaGuide Server-Safe's step cards.
-- scripted: 'full' (the server implements the whole quest), 'partial', or 'stub'.
--
-- Copyright (c) 2026 Bates LLC.  All rights reserved.

local T = {}

"""


INTERNAL = re.compile(r"(?<![A-Za-z0-9'])(_[0-9a-z]{2,4}|[A-Z]{1,3}_[A-Za-z_]+|qm\d+)(?![A-Za-z0-9])")


def display_names(sql):
    """{internal npc name: display name} from npc_list.sql, where the name is unambiguous.
    Doors and objects are named like '_6s1' or 'TR_Entrance' in scripts; players see
    'Door:"Marble Bridge"' or 'Transcendental Radiance'."""
    seen = {}
    if sql and os.path.exists(sql):
        for m in re.finditer(r"VALUES \(\d+,'([^']*)','((?:[^'\\]|\\.)*)'", open(sql, encoding='utf-8', errors='replace').read()):
            seen.setdefault(m.group(1), set()).add(m.group(2).replace("\\'", "'"))
    out = {}
    for name, shown in seen.items():
        shown = {v for v in shown if v and not v.startswith('TEST_')}
        if len(shown) == 1:
            v = shown.pop()
            d = re.match(r'Door:\s*"?([^"]*)"?', v)
            out[name] = 'the door "%s"' % d.group(1) if d else v
        elif shown and all(v.startswith('Door:') for v in shown):
            out[name] = 'the door'                 # same id, different doors per zone
        elif not shown:
            out[name] = 'the unmarked spot'        # an invisible event trigger
    return out


def clean(step, names=None):
    step = ' '.join(str(step).split())
    if names is not None:
        def swap(m):
            k = m.group(1)
            if re.fullmatch(r'qm\d+', k):
                return 'the "???" spot'
            return names.get(k, k)
        step = INTERNAL.sub(swap, step)
    return step


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('entries')
    ap.add_argument('-o', '--out', default='Vanaguide/data/quest_steps.lua')
    ap.add_argument('--npcs', help='sql/npc_list.sql, to show doors and objects by their in-game names')
    args = ap.parse_args()
    names = display_names(args.npcs)
    tables = {'quest': defaultdict(dict), 'mission': defaultdict(dict)}
    for e in json.load(open(args.entries, encoding='utf-8')):
        steps = [clean(s, names) for s in e.get('steps', []) if clean(s)]
        if e.get('kind') in tables and steps and isinstance(e.get('id'), (int, float)):
            tables[e['kind']][e['area']][int(e['id'])] = (e.get('scripted', 'full'), steps)
    with open(args.out, 'w', encoding='utf-8') as fh:
        fh.write(HEADER)
        for kind, name in (('quest', 'quests'), ('mission', 'missions')):
            fh.write('T.%s = {\n' % name)
            for area in sorted(tables[kind]):
                fh.write('    %s = {\n' % area)
                for qid in sorted(tables[kind][area]):
                    scripted, steps = tables[kind][area][qid]
                    fh.write('        [%d] = { scripted = %s, steps = { %s } },\n'
                             % (qid, lua_str(scripted), ', '.join(lua_str(s) for s in steps)))
                fh.write('    },\n')
            fh.write('}\n\n')
        fh.write('return T\n')
    n = {k: sum(len(v) for v in t.values()) for k, t in tables.items()}
    print('%d quests, %d missions with steps' % (n['quest'], n['mission']))


if __name__ == '__main__':
    main()
