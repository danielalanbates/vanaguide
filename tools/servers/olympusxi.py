def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--raw', default=os.path.expanduser('~/Downloads/ffxi-server-data/%s/raw' % KEY))
    ap.add_argument('--out', default=os.path.join(REPO_ROOT, 'Vanaguide/data/servers', KEY))
    ap.add_argument('--refresh', action='store_true')
    ap.add_argument('--fetch-only', action='store_true')
    a = ap.parse_args()
    report = fetch_all(a.raw, a.refresh)
    print(json.dumps({k: report.get(k) for k in ('fetched', 'blocked', 'notes')}, indent=1))
    if a.fetch_only:
        return
    pack = Pack(os.path.join(a.raw, 'wiki'))
    os.makedirs(a.out, exist_ok=True)
    man = pack.manifest

    def header(fname, what=''):
        return ('-- Vanaguide :: data/servers/%s/%s\n'
                '-- GENERATED by tools/servers/%s.py from the Olympus Wiki pack %s (%s) and %s, fetched %s.  Do not hand-edit.\n'
                '-- %s\n'
                '-- Source data belongs to Olympus XI (Olympus Games); no licence is stated by the source.\n'
                '--\n-- Copyright (c) 2026 Bates LLC.  All rights reserved.\n\n'
                % (KEY, fname, KEY, man.get('version'), RELEASE_URL, SITE, FETCHED, what or 'Read by VanaGuide Server-Safe.'))

    rows = gear(pack)
    count = write_gear(rows, os.path.join(a.out, 'gear_guide.lua'), header)
    count = dict(count)
    count['_total'] = len(rows)
    sk = skills(pack)
    write_guides(sk, os.path.join(a.out, 'skill_guides.lua'),
                 header('skill_guides.lua', 'Craft levelling bands from Olympus XI\'s own recipes and shop prices.'))
    qg = quest_guides(pack)
    write_guides(qg, os.path.join(a.out, 'quest_guides.lua'),
                 header('quest_guides.lua', 'Quests and missions; walkthroughs where the pack has one.'))
    notes, dropped = server_notes(pack, a.raw, report, count, len(pack.quests), len(pack.missions))
    write_guides(notes, os.path.join(a.out, 'server_notes.lua'),
                 header('server_notes.lua', 'Server facts: every bullet appears on the fetched page named in the guide\'s Source.'))
    print('gear items %d %s' % (len(rows), {k: v for k, v in count.items() if not k.startswith('_')}))
    print('skill guides %d, quest guides %d, server notes %d' % (len(sk), len(qg), len(notes)))
    for d in dropped:
        print('DROPPED note (not found on page):', d)


if __name__ == '__main__':
    sys.exit(main())
