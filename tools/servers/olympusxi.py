def server_notes(pack, raw, report, gear_count, nq, nm):
    texts, dropped = {}, []
    for f in os.listdir(os.path.join(raw, 'site')):
        if f.endswith('.html'):
            texts[f[:-5].replace('__', '/')] = page_text(os.path.join(raw, 'site', f))
    guides = []
    blocked = report.get('blocked', [])
    man = pack.manifest
    lic = None
    try:
        lic = (json.load(open(os.path.join(raw, 'repo.json'))).get('license') or {}).get('spdx_id')
    except (OSError, ValueError):
        pass
    npc_only = sum(1 for v in pack.quests.values() if v.get('impl') == 'npc')
    about = [
        ('What was fetched', '\n'.join([
            '• The Olympus Wiki data pack (the /owiki data the Olympus XI launcher downloads), version %s, built %s: '
            'GitHub release "%s" of %s, read through the GitHub REST API; sha256 checked against GitHub and the pack\'s own manifest.'
            % (man.get('version'), man.get('built'), TAG, REPO),
            '• The pack\'s own counts: %s.' % ', '.join('%s %s' % (v, k) for k, v in man.get('counts', {}).items()),
            '• Website pages from %s/sitemap.xml: %s.' % (SITE, ', '.join(sorted('/' + k if k != 'index' else '/' for k in texts))),
            '• Fetched %s.' % FETCHED])),
        ('What these files hold', '\n'.join([
            '• Gear: %d items from the pack (%s).' % (gear_count.get('_total', 0),
                                                      ', '.join('%s %d' % (k, v) for k, v in gear_count.items() if not k.startswith('_'))),
            '• Skills: crafting bands built from the pack\'s %d recipes and its merchant and guild shop prices.' % len(pack.recipes),
            '• Quests: %d quests and %d missions; %d quests are marked impl=npc in the pack and are labelled not fully scripted on this server.' % (nq, nm, npc_only),
            '• Server notes: sentences taken from the website; each was checked against the fetched page.'])),
        ('Not covered', '\n'.join([
            '• Combat and magic skill caps, and fishing skill levels: the pack does not include them.',
            '• Ballista point exchange stock, Angler\'s Mark exchange stock and EXP/drop rate multipliers by number: no fetched page lists them.',
            '• Level, slot and jobs of the Olympus-only notorious monster gear: the pack gives only names and stats text.',
            '• Leaderboards, the Hall of the Fallen and other live player data: left out on purpose.',
            '• Pages robots.txt disallows (%s/api/, %s/download) were not requested.' % (SITE, SITE)]
            + ['• Not fetched: %s.' % b for b in blocked])),
        ('Licence', '\n'.join([
            '• No licence is stated on the website or the release; the repository licence reported by GitHub: %s.' % (lic or 'none'),
            '• Olympus XI and its wiki data belong to its team (Olympus Games). This is a pointer for players, not a copy of their wiki: walkthroughs are summarised from the pack.',
            '• Website footer: Olympus XI is a fan-run project and is not affiliated with or endorsed by Square Enix. Powered by LandSandBoat.'])),
    ]
    guides.append(('About this data', 'Server', 'What was fetched for Olympus XI, when, and what is not covered. Source: %s ; %s'
                   % (RELEASE_URL, SITE), about))
    for topic, subs in NOTES:
        steps, urls = [], []
        for title, bullets in subs:
            lines = []
            for page, text, *label in bullets:
                key = page or 'index'
                body = texts.get(key, '')
                found = body.lower().find(norm_ws(text).lower())
                if found >= 0 and label and label[0].startswith('News of '):
                    dates = re.findall(r'(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) \d{1,2}, \d{4}', body[:found])
                    if not dates or 'News of ' + dates[-1] != label[0]:
                        found = -1                  # the post's own date heading does not match the label
                if found >= 0:
                    lines.append('• ' + ('%s: ' % label[0] if label else '') + text.rstrip())
                    u = SITE + ('/' + page if page else '')
                    if u not in urls:
                        urls.append(u)
                else:
                    dropped.append((topic, page, text))
            if lines:
                steps.append((title, '\n'.join(lines)))
        if topic == 'Gear and drops':
            lines = []
            for key, lv in pack.lore.items():
                zs = sorted({pack.mobs.get(m, {}).get('z') for m in lv.get('mobs', [])} - {None})
                names = [pack.mobs.get(m, {}).get('n', m) for m in lv.get('mobs', [])]
                where = (': %s in %s' % (', '.join(names), ', '.join(pack.zone(z) for z in zs))) if names and zs else ''
                lines.append('• %s (%s)%s' % (lv['t'], lv.get('sub', ''), where))
            steps.append(('Story monsters in the Olympus Wiki', '\n'.join(lines)))
            urls.append(RELEASE_URL)
        if topic == 'Quests and missions':
            steps.append(('In the Olympus Wiki pack', '\n'.join([
                '• %d quests and %d missions, %d step-by-step walkthroughs.' % (len(pack.quests), len(pack.missions), len(pack.guides)),
                '• %d quests are marked impl=npc (NPCs present, quest not fully scripted); the rest are marked impl=full.' % npc_only])))
            urls.append(RELEASE_URL)
        if steps:
            guides.append((topic, 'Server', 'Olympus XI: %s, from the server\'s website%s. Source: %s'
                           % (topic.lower(), ' and wiki pack' if RELEASE_URL in urls else '', ' ; '.join(urls)), steps))
    return guides, dropped


def write_guides(guides, path, header, var='S'):
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(header)
        fh.write('local S = {}\n\nS.guides = {\n')
        for name, group, desc, steps in guides:
            fh.write('    { name = %s, group = %s, desc = %s, steps = {\n' % (q(name), q(group), q(desc)))
            fh.write(',\n'.join('            { title = %s, note = %s }' % (q(t), q(n)) for t, n in steps))
            fh.write('\n    } },\n')
        fh.write('}\n\nreturn S\n')


