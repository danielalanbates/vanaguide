CRAFT_RANKS = {0: 'Amateur', 1: 'Recruit', 2: 'Initiate', 3: 'Novice', 4: 'Apprentice', 5: 'Journeyman',
               6: 'Craftsman', 7: 'Artisan', 8: 'Adept', 9: 'Veteran'}


def skills(pack):
    buy = defaultdict(list)                      # item -> [(price, npc, zone)]
    for iid, it in pack.items.items():
        for s in it.get('shop', []):
            # f=6 with o>0 marks a guild-rank shop entry (LSB generalGuildStock): o is the craft rank needed.
            gate = s.get('o', 0) if s.get('f') == 6 else 0
            buy[iid].append((gate > 0, s['p'], s['n'], s['z'], gate))
        for s in it.get('gshop', []):
            buy[iid].append((False, s.get('max') or s['p'], s['n'], s['z'], 0))
    per = defaultdict(list)
    for rid, r in pack.recipes.items():
        if r.get('ds') or r['res'] not in pack.items:
            continue
        c = defaultdict(int)
        for i in r['ing']:
            c[i] += 1
        cost, ok, parts = 0, True, []
        for i, n in c.items():
            src = sorted(buy.get(i, []))
            nm = ('%d × ' % n if n > 1 else '') + pack.iname(i)
            if src:
                _, price, npc, z, gate = src[0]
                cost += price * n
                parts.append('%s (%s, %s, %d gil%s)' % (nm, npc, pack.zone(z), price,
                                                       ', sold only to guild rank %s or higher' % CRAFT_RANKS.get(gate, gate) if gate else ''))
            else:
                ok, cost = False, cost + 10 ** 6
                parts.append(nm)
        for ci, lv in enumerate(r['lv']):
            if lv:
                others = sorted(((x, pack.crafts[j]) for j, x in enumerate(r['lv']) if j != ci and x), reverse=True)
                other = others[0][0] if others else 0
                need = ', '.join('%s %d' % (c, x) for x, c in others)
                per[ci].append((lv, pack.iname(r['res']), pack.iname(r['cr']), parts, cost, ok, other, bool(r.get('ki')), need))
    out = []
    for ci, craft in enumerate(pack.crafts):
        steps = []
        for lo in range(0, 110, 10):
            band = [x for x in per[ci] if lo < x[0] <= lo + 10]
            if not band:
                continue
            band.sort(key=lambda x: (x[6] > lo, x[7], not x[5], x[4], x[0]))
            picked, seen = [], set()
            for x in band:
                if x[1] not in seen:
                    seen.add(x[1])
                    picked.append(x)
            lines = ['• %s (cap %d)%s%s: %s + %s' % (name, lv, '' if other == 0 else ', also needs %s' % need,
                                                     ', needs a key item' if ki else '', crystal, ', '.join(parts))
                     for lv, name, crystal, parts, cost, ok, other, ki, need in picked[:4]]
            steps.append(('%s %d–%d' % (craft, lo, lo + 10), '\n'.join(lines)))
        out.append((craft, 'Crafting', 'In each band, synthesize one of these until it stops giving skill, then move on. '
                    'Cheapest first, using Olympus XI\'s own recipes and shop prices; ingredients any new player can buy are '
                    'preferred over ones a guild sells only at a higher craft rank. Merchant prices are base prices '
                    '(nation fame can move some of them a little); guild shop prices are the most they charge.', steps))
    return out


