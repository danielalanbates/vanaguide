def clean_markup(s, pack):
    def pin(m):
        before = s[max(0, m.start() - 80):m.start()]
        label, x, y = m.group(4), m.group(2), m.group(3)
        return '' if label in before else ' (%s, map position %s, %s)' % (label, x, y)
    s = re.sub(r'\{map:(-?\d+):(-?[\d.]+):(-?[\d.]+)\|([^}]*)\}', pin, s)
    s = re.sub(r'\{map:[^}]*\}', '', s)
    s = re.sub(r'\[\[item:(\d+)\]\]', lambda m: pack.iname(int(m.group(1))), s)
    s = re.sub(r'\[\[[a-z]+:[^\]|]*\|([^\]]*)\]\]', r'\1', s)
    s = re.sub(r'\[\[[^\]]*\]\]', '', s)
    s = re.sub(r'\{(?:ki|done|have)[^}]*\}', '', s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'\1', s)
    s = re.sub(r'[ \t]+([.,;:])', r'\1', s)
    return re.sub(r'[ \t]{2,}', ' ', s).strip()


def guide_steps(body, pack):
    """Markdown walkthrough -> (intro, [(title, note)])."""
    parts = re.split(r'^## (.+)$', body, flags=re.M)
    intro = clean_markup(parts[0], pack)
    steps = []
    for head, text in zip(parts[1::2], parts[2::2]):
        items = [clean_markup(re.sub(r'^\s*[-*]\s*(\[[ x]\]\s*)?', '', ln), pack)
                 for ln in text.splitlines() if re.match(r'\s*[-*]\s', ln)]
        paras = [clean_markup(p, pack) for p in re.split(r'\n\s*\n', text) if p.strip() and not re.match(r'\s*[-*]\s', p)]
        if head.strip().lower() == 'steps':
            for n, it in enumerate(items, 1):
                steps.append(('Step %d' % n, it))
            for p in paras:
                steps.append(('Note', p))
        else:
            lines = ['• ' + x for x in paras + items if x]
            if lines:
                steps.append((head.strip(), '\n'.join(lines)))
    return intro, steps


def client_zone_conflict(v, pack):
    """The pack's client text names a zone, but its NPC record for the same person is in another zone."""
    client = v.get('client') or ''
    named = [z for z in sorted(set(pack.zones.values()), key=len, reverse=True) if z in client]
    if not named:
        return None
    for n in v.get('npcs', []):
        if n['n'] and n['n'] in client and n.get('z') in pack.zones and pack.zone(n['z']) not in named:
            return ('• The pack contradicts itself: its quest text puts %s in %s, but its NPC record places %s in %s. '
                    'Look in both.' % (n['n'], named[0], n['n'], pack.zone(n['z'])))
    return None


def fact_steps(v, pack, kind):
    steps = []
    if v.get('client'):
        steps.append(('Start', '• Talk to %s.' % v['client']))
    req = v.get('req') or {}
    rl = []
    if req.get('lv'):
        rl.append('• Level %d or higher.' % req['lv'])
    if req.get('job'):
        rl.append('• Job: %s.' % ', '.join(req['job']))
    for f in req.get('fame', []):
        rl.append('• %s fame level %d.' % (f[0], f[1]))
    for log, i in req.get('quests', []):
        if (log, i) in pack.quests:
            rl.append('• Quest done first: %s.' % pack.quests[(log, i)]['n'])
    for log, i in req.get('missions', []):
        if (log, i) in pack.missions:
            rl.append('• Mission done first: %s.' % pack.missions[(log, i)]['n'])
    if req.get('crystals'):
        rl.append('• Trade %d crystals to a gate guard to be offered it.' % req['crystals'])
    if rl:
        steps.append(('Requirements', '\n'.join(rl)))
    kin = {int(k): v2 for k, v2 in (v.get('kiNames') or {}).items()}
    if v.get('trade'):
        steps.append(('Items to trade', '\n'.join('• %s%s' % ('%d × ' % n if n > 1 else '', pack.iname(i) if i != 65535 else 'gil')
                                                 if i != 65535 else '• %d gil' % n for i, n in v['trade'])))
    if v.get('kiNeed'):
        steps.append(('Key items needed', '\n'.join('• ' + kin.get(k, 'key item %d' % k) for k in v['kiNeed'])))
    if v.get('kiGet'):
        steps.append(('Key items you get', '\n'.join('• ' + kin.get(k, 'key item %d' % k) for k in v['kiGet'])))
    if v.get('fights') or v.get('battles'):
        steps.append(('Fights', '\n'.join(['• ' + f for f in v.get('fights', [])] +
                                          ['• Battlefield: ' + b for b in v.get('battles', [])])))
    if v.get('npcs'):
        seen, lines = {}, []
        for n in v['npcs']:
            lab = npc_label(n['n'])
            if lab is None:
                continue
            key = (lab, pack.zone(n.get('z')))
            if key not in seen:
                seen[key] = len(lines)
                lines.append([lab, key[1], 1])
            else:
                lines[seen[key]][2] += 1
        out = ['• %s%s (%s)' % (lab, ' ×%d' % c if c > 1 else '', z) for lab, z, c in lines[:8]]
        if out:
            steps.append(('NPCs involved', '\n'.join(out)))
    conflict = client_zone_conflict(v, pack)
    if conflict:
        steps.append(('Check in game', conflict))
    rw = v.get('reward') or {}
    rwl = ['• %s%s' % ('%d × ' % n if n > 1 else '', pack.iname(i)) for i, n in rw.get('items', [])]
    if rw.get('gil'):
        rwl.append('• %d gil' % rw['gil'])
    if rw.get('exp'):
        rwl.append('• %d EXP' % rw['exp'])
    for k in rw.get('ki', []):
        rwl.append('• Key item: ' + kin.get(k, 'key item %d' % k))
    if rw.get('fame'):
        rwl.append('• %s fame +%d' % (rw['fame'][0], rw['fame'][1]))
    if rw.get('title'):
        rwl.append('• Title: ' + rw['title'])
    if rw.get('rankPoints'):
        rwl.append('• %d rank points' % rw['rankPoints'])
    if rw.get('rank'):
        rwl.append('• Rank %d' % rw['rank'])
    if rwl:
        steps.append(('Reward', '\n'.join(rwl)))
    return steps


def quest_guides(pack):
    out = []
    for (log, i), v in sorted(pack.quests.items()):
        desc = v.get('sum', '').strip()
        if v.get('client'):
            desc += ' Given by %s.' % v['client']
        if v.get('impl') == 'npc':
            desc += ' Not fully scripted on this server (the pack marks it impl=npc): the NPCs are there but the quest may not work end to end.'
        g = pack.guides.get('q:%d:%d' % (log, i))
        steps = []
        if g:
            intro, steps = guide_steps(g['body'], pack)
            if intro:
                steps.insert(0, ('Overview', '\n'.join('• ' + p.strip() for p in re.split(r'\n\s*\n', intro) if p.strip())))
        steps += [s for s in fact_steps(v, pack, 'quest') if not g or s[0] in ('Reward',)]
        out.append((v['n'], pack.qlogs.get(log, str(log)), desc.strip(), steps))
    for (log, i), v in sorted(pack.missions.items()):
        desc = v.get('sum', '').strip()
        g = pack.guides.get('m:%d:%d' % (log, i))
        steps = []
        if g:
            intro, steps = guide_steps(g['body'], pack)
            if intro:
                steps.insert(0, ('Overview', '\n'.join('• ' + p.strip() for p in re.split(r'\n\s*\n', intro) if p.strip())))
        steps += [s for s in fact_steps(v, pack, 'mission') if not g or s[0] in ('Reward',)]
        out.append(('%s: %s' % (v.get('label') or 'Mission', v['n']), '%s Missions' % pack.mlogs.get(log, str(log)),
                    desc, steps))
    return out


