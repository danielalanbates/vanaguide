_last = {}


def get(url, accept=None, min_gap=1.0):
    host = urllib.parse.urlsplit(url).netloc
    wait = _last.get(host, 0) + min_gap - time.time()
    if wait > 0:
        time.sleep(wait)
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    if accept:
        req.add_header('Accept', accept)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status, r.read()
    finally:
        _last[host] = time.time()


def save(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data)


def robots_rules(text, agents=('claudebot', 'anthropic-ai', 'claude-web', '*')):
    """{agent: [(allow? | 'delay', value)]} for the groups that name our agents."""
    groups, cur, in_rules = {}, [], False
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        if ':' not in line:
            continue
        k, v = [x.strip() for x in line.split(':', 1)]
        k = k.lower()
        if k == 'user-agent':
            if in_rules:
                cur, in_rules = [], False
            cur.append(v.lower())
            for a in cur:
                groups.setdefault(a, [])
        elif k in ('allow', 'disallow', 'crawl-delay'):
            in_rules = True
            for a in cur:
                groups[a].append(('delay' if k == 'crawl-delay' else k == 'allow', v))
    return {a: groups[a] for a in agents if a in groups}


def _match(pattern, path):
    if not pattern:
        return False
    rx = re.escape(pattern).replace(r'\*', '.*')
    if rx.endswith(r'\$'):
        rx = rx[:-2] + '$'
    return re.match(rx, path) is not None


def allowed(rules, path):
    """Longest match wins per agent; any of our agents disallowing means disallowed."""
    for agent, rs in rules.items():
        best = None
        for allow, pat in rs:
            if allow == 'delay':
                continue
            if _match(pat, path) and (best is None or len(pat) > len(best[1])):
                best = (allow, pat)
        if best and not best[0]:
            return False, '%s: Disallow %s' % (agent, best[1])
    return True, ''


def fetch_all(raw, refresh=False):
    os.makedirs(raw, exist_ok=True)
    report = {'fetched': [], 'blocked': [], 'notes': []}

    def need(p):
        return refresh or not os.path.exists(p)

    robots = {}
    for host, name in (('https://github.com', 'robots_github.txt'),
                       ('https://api.github.com', 'robots_api_github.txt'),
                       ('https://release-assets.githubusercontent.com', 'robots_release_assets.txt'),
                       (SITE, 'robots_olympus.txt')):
        p = os.path.join(raw, name)
        if need(p):
            try:
                code, data = get(host + '/robots.txt')
            except urllib.error.HTTPError as e:
                code, data = e.code, b''
            save(p, data if code == 200 else b'')
            report['fetched'].append('%s/robots.txt (HTTP %s)' % (host, code))
        txt = open(p, encoding='utf-8', errors='replace').read()
        robots[host] = robots_rules(txt) if re.match(r'\s*(user-agent|#|sitemap|allow|disallow)', txt, re.I) else {}

    ok, why = allowed(robots['https://github.com'], '/%s/releases/download/%s/wiki.json' % (REPO, TAG))
    if not ok:
        report['blocked'].append('https://github.com/%s/releases/download/%s/* (github.com robots.txt %s); '
                                 'read through the api.github.com release API instead' % (REPO, TAG, why))

    for name, url in (('release_wiki.json', 'https://api.github.com/repos/%s/releases/tags/%s' % (REPO, TAG)),
                      ('repo.json', 'https://api.github.com/repos/%s' % REPO)):
        p = os.path.join(raw, name)
        if need(p):
            code, data = get(url, accept='application/vnd.github+json')
            save(p, data)
            report['fetched'].append(url)
    meta = json.load(open(os.path.join(raw, 'release_wiki.json')))
    assets = {a['name']: a for a in meta.get('assets', [])}

    def asset(name):
        a = assets[name]
        p = os.path.join(raw, name)
        if need(p):
            url = 'https://api.github.com/repos/%s/releases/assets/%d' % (REPO, a['id'])
            code, data = get(url, accept='application/octet-stream')
            save(p, data)
            report['fetched'].append('%s (%s)' % (url, name))
        h = hashlib.sha256(open(p, 'rb').read()).hexdigest()
        dig = (a.get('digest') or '').replace('sha256:', '')
        if dig and dig != h:
            raise SystemExit('sha256 mismatch for %s: GitHub says %s, file is %s' % (name, dig, h))
        return p, h

    man_p, _ = asset('wiki.json')
    man = json.load(open(man_p))
    zname = os.path.basename((man.get('file') or man.get('filename') or 'wiki-%s.zip' % man['version']).replace('\\', '/'))
    zp, zh = asset(zname)
    if man.get('sha256') and man['sha256'].lower() != zh:
        raise SystemExit('wiki.json sha256 %s != %s %s' % (man['sha256'], zname, zh))
    report['notes'].append('wiki.json version %s; %s sha256 %s verified' % (man.get('version'), zname, zh))

    out = os.path.join(raw, 'wiki')
    stamp = os.path.join(out, '.from')
    if refresh or not os.path.exists(stamp) or open(stamp).read() != zh:
        with zipfile.ZipFile(zp) as z:
            for info in z.infolist():
                n = info.filename.replace('\\', '/')
                parts = [x for x in n.split('/') if x not in ('', '.', '..')]
                if not parts or n.endswith('/'):
                    continue
                dst = os.path.join(out, *parts)
                if not os.path.abspath(dst).startswith(os.path.abspath(out) + os.sep):
                    continue
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                with z.open(info) as src, open(dst, 'wb') as f:
                    f.write(src.read())
        with open(stamp, 'w') as f:
            f.write(zh)

    srules = robots[SITE]
    delay = 1.0
    for rs in srules.values():
        for k, v in rs:
            if k == 'delay':
                try:
                    delay = max(delay, float(v))
                except ValueError:
                    pass
    sm = os.path.join(raw, 'site', 'sitemap.xml')
    if need(sm):
        code, data = get(SITE + '/sitemap.xml', min_gap=delay)
        save(sm, data)
        report['fetched'].append(SITE + '/sitemap.xml')
    locs = re.findall(r'<loc>\s*([^<\s]+)\s*</loc>', open(sm, encoding='utf-8').read())
    for u in locs:
        sp = urllib.parse.urlsplit(u)
        if sp.netloc != urllib.parse.urlsplit(SITE).netloc:
            continue
        path = sp.path or '/'
        ok, why = allowed(srules, path)
        if not ok:
            report['blocked'].append('%s (robots.txt %s)' % (u, why))
            continue
        p = os.path.join(raw, 'site', page_file(u))
        if need(p):
            try:
                code, data = get(u, min_gap=delay)
            except urllib.error.HTTPError as e:
                report['blocked'].append('%s (HTTP %s)' % (u, e.code))
                continue
            save(p, data)
            report['fetched'].append(u)
    old = {}
    rp = os.path.join(raw, 'fetch_report.json')
    if os.path.exists(rp):
        old = json.load(open(rp))
    merged = {'pages': locs, 'manifest': man, 'zip_sha256': zh,
              'fetched': old.get('fetched', []) + [x for x in report['fetched'] if x not in old.get('fetched', [])],
              'blocked': sorted(set(old.get('blocked', []) + report['blocked'])),
              'notes': report['notes']}
    with open(rp, 'w') as f:
        json.dump(merged, f, indent=1)
    return merged


def page_file(url):
    path = urllib.parse.urlsplit(url).path.strip('/')
    return ('index' if not path else path.replace('/', '__')) + '.html'


# ----------------------------------------------------------------- data-only Lua literal parser
_TOK = re.compile(r'''
    (?P<ws>\s+|--\[(?P<eq>=*)\[.*?\](?P=eq)\]|--[^\n]*)
  | (?P<lstr>\[(?P<leq>=*)\[.*?\](?P=leq)\])
  | (?P<str>"(?:[^"\\\n]|\\.|\\\n)*"|'(?:[^'\\\n]|\\.|\\\n)*')
  | (?P<num>0[xX][0-9a-fA-F]+|(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)
  | (?P<name>[A-Za-z_][A-Za-z_0-9]*)
  | (?P<op>[{}\[\]=,;\-])
''', re.S | re.X)
_ESC = {'n': '\n', 't': '\t', 'r': '\r', 'a': '\a', 'b': '\b', 'f': '\f', 'v': '\v',
        '\\': '\\', '"': '"', "'": "'", '\n': '\n'}


def _unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c != '\\':
            out.append(c)
            i += 1
            continue
        i += 1
        c = s[i]
        if c in _ESC:
            out.append(_ESC[c])
            i += 1
        elif c.isdigit():
            m = re.match(r'\d{1,3}', s[i:])
            out.append(chr(int(m.group())))
            i += len(m.group())
        elif c == 'x':
            out.append(chr(int(s[i + 1:i + 3], 16)))
            i += 3
        elif c == 'z':
            i += 1
            while i < len(s) and s[i].isspace():
                i += 1
        elif c == 'u':
            m = re.match(r'u\{([0-9a-fA-F]+)\}', s[i:])
            out.append(chr(int(m.group(1), 16)))
            i += len(m.group())
        else:
            raise ValueError('bad escape \\' + c)
    return ''.join(out)


def _tokens(src):
    pos, n = 0, len(src)
    while pos < n:
        m = _TOK.match(src, pos)
        if not m:
            raise ValueError('unexpected %r at %d' % (src[pos:pos + 20], pos))
        pos = m.end()
        if m.group('ws') is not None:
            continue
        if m.group('lstr') is not None:
            eq = len(m.group('leq'))
            s = m.group('lstr')[2 + eq:-(2 + eq)]
            yield ('str', s[1:] if s.startswith('\n') else s)
        elif m.group('str') is not None:
            yield ('str', _unescape(m.group('str')[1:-1]))
        elif m.group('num') is not None:
            t = m.group('num')
            if t.lower().startswith('0x'):
                yield ('num', int(t, 16))
            elif t.isdigit():
                yield ('num', int(t))
            else:
                yield ('num', float(t))
        elif m.group('name') is not None:
            yield ('name', m.group('name'))
        else:
            yield ('op', m.group('op'))


class _Parser:
    def __init__(self, src):
        self.t = list(_tokens(src))
        self.i = 0

    def peek(self, k=0):
        return self.t[self.i + k] if self.i + k < len(self.t) else (None, None)

    def take(self, kind, val=None):
        tok = self.peek()
        if tok[0] != kind or (val is not None and tok[1] != val):
            raise ValueError('expected %s %s, got %r' % (kind, val, tok))
        self.i += 1
        return tok

    def value(self):
        k, v = self.peek()
        if k in ('str', 'num'):
            self.i += 1
            return v
        if (k, v) == ('op', '-'):
            self.i += 1
            return -self.take('num')[1]
        if (k, v) == ('op', '{'):
            return self.table()
        if k == 'name' and v in ('true', 'false', 'nil'):
            self.i += 1
            return {'true': True, 'false': False, 'nil': None}[v]
        raise ValueError('not a data literal: %r (refusing to evaluate)' % ((k, v),))

    def table(self):
        self.take('op', '{')
        d, n, keyed = {}, 1, False
        while self.peek() != ('op', '}'):
            k, v = self.peek()
            if (k, v) == ('op', '['):
                self.i += 1
                key = self.value()
                self.take('op', ']')
                self.take('op', '=')
                d[key] = self.value()
                keyed = True
            elif k == 'name' and self.peek(1) == ('op', '=') and v not in ('true', 'false', 'nil'):
                self.i += 2
                d[v] = self.value()
                keyed = True
            else:
                d[n] = self.value()
                n += 1
            if self.peek() in (('op', ','), ('op', ';')):
                self.i += 1
            elif self.peek() != ('op', '}'):
                raise ValueError('expected , or }, got %r' % (self.peek(),))
        self.take('op', '}')
        if not keyed:                            # a pure array constructor; explicit [k]= stays a dict
            return [d[i] for i in range(1, len(d) + 1)]
        return d


def load_lua(path):
    p = _Parser(open(path, encoding='utf-8').read())
    p.take('name', 'return')
    v = p.value()
    if p.i != len(p.t):
        raise ValueError('%s: trailing tokens after the returned table' % path)
    return v


# ------------------------------------------------------------------------------------ helpers
def q(s):
    s = str(s).replace('\\', '\\\\').replace("'", "\\'").replace('\r', '').replace('\n', '\\n')
    return "'" + s + "'"


def jobs_text(jobs):
    if not jobs or set(jobs) >= set(JOBS):
        return 'All jobs'
    return ' '.join(j for j in JOBS if j in jobs)


def slot_name(mask):
    for bit, name in SLOTS:
        if mask & bit:
            return name
    return 'other'


def pct(d):
    """The pack gives a drop group's rate out of 10000 (`r`) and the item's share of that group (`s`)."""
    return '%.1f%%' % (d.get('r', 0) * d.get('s', 1) / 100.0)


class Text(HTMLParser):
    SKIP = {'script', 'style', 'noscript', 'svg', 'head', 'template'}
    BLOCK = {'p', 'div', 'li', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'br', 'tr', 'section', 'article',
             'header', 'footer', 'nav', 'ul', 'ol', 'table', 'main', 'dt', 'dd', 'blockquote', 'pre', 'td'}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out, self.skip = [], 0

    def handle_starttag(self, t, a):
        if t in self.SKIP:
            self.skip += 1
        if t in self.BLOCK:
            self.out.append('\n')

    def handle_endtag(self, t):
        if t in self.SKIP and self.skip:
            self.skip -= 1
        if t in self.BLOCK:
            self.out.append('\n')

    def handle_data(self, d):
        if not self.skip:
            self.out.append(d)


def page_text(path):
    p = Text()
    p.feed(open(path, encoding='utf-8', errors='replace').read())
    t = html.unescape(''.join(p.out))
    return norm_ws(t)


def norm_ws(t):
    t = t.replace('\u2019', "'").replace('\u2018', "'").replace('\u201c', '"').replace('\u201d', '"')
    return re.sub(r'\s+', ' ', t)


# --------------------------------------------------------------------------------- text tidy
# The pack's quest/mission strings were scraped from wiki pages and carry a few artifacts:
# line-break hyphens ("counter- feit"), a '+' marker in front of some quest names, the
# "Aht Uhrgan" misspelling in ToAU mission labels, and leftover "Clients: ... Summary" labels.
CLOSED_WORDS = {'counterfeit', 'masterpiece'}


def tidy(s):
    s = s.replace('Uhrgan', 'Urhgan')
    s = re.sub(r'(\w+)- (\w+)', lambda m: (m.group(1) + m.group(2)) if (m.group(1) + m.group(2)).lower() in CLOSED_WORDS
               else m.group(1) + '-' + m.group(2), s)
    s = re.sub(r'^\+(?=\S)', '', s.strip())
    return s


def split_summary(s):
    """'Clients: X Summary Y' / 'Summary: Y' / '<cut-off text>) Summary: Y' -> (Y, X or None)."""
    m = re.match(r'^(.*?)\bSummary:?\s+(.*)$', s, flags=re.S)
    if not m or (m.group(1) and not re.match(r'^Clients?:|.*\)\s*$', m.group(1).strip())):
        return s, None
    pre = m.group(1).strip()
    who = re.match(r'^Clients?:\s*(.+)$', pre)
    return m.group(2).strip(), (who.group(1).strip() if who else None)


# Internal LSB entity names (qm7, _6r9 door ids, region triggers) -> what a player sees.
def npc_label(name):
    n = name.strip()
    if re.match(r'^(blank\b|Region \d|\d+\.\s)', n):
        return None                                   # invisible trigger or a step text, not an NPC
    paren = re.findall(r'\(([^)]*)\)', n)
    extra = [x.strip() for x in paren if x.strip() and x.strip() != '???' and not re.match(r'^\s*\w{3}$', x.strip())]
    base = re.sub(r'\([^)]*\)', '', n).strip()
    if re.match(r'^qm(\d+|\b)', base, flags=re.I):
        return '???' + (' (%s)' % ', '.join(extra) if extra else '')
    if re.match(r'^\w{3}$', base) and re.search(r'\d', base) or base == '':
        return ', '.join(extra) if extra else 'unnamed door or object'
    base = re.sub(r'^\w{3}\s+-\s+', '', base) if re.match(r'^\w{3}\s+-\s+', base) and re.search(r'\d', base[:3]) else base
    base = re.sub(r'(?<=[a-z])\d+$', '', base)          # Toads Footprint2 -> Toads Footprint
    return base + (' (%s)' % ', '.join(extra) if extra else '')


# ------------------------------------------------------------------------------------ the pack
class Pack:
    def __init__(self, wiki):
        man = json.load(open(os.path.join(wiki, 'manifest.json')))
        for shard, info in man.get('shards', {}).items():
            p = os.path.join(wiki, shard + '.lua')
            if os.path.exists(p) and hashlib.sha256(open(p, 'rb').read()).hexdigest() != info['sha256']:
                raise SystemExit('shard %s does not match manifest.json' % shard)
        self.manifest = man
        self.meta = load_lua(os.path.join(wiki, 'meta.lua'))
        self.zones = {z: v['n'] for z, v in self.meta['zones'].items()}
        self.items = {}
        for f in os.listdir(os.path.join(wiki, 'items')):
            if f.endswith('.lua'):
                self.items.update(load_lua(os.path.join(wiki, 'items', f)))
        self.recipes = load_lua(os.path.join(wiki, 'recipes.lua'))
        self.guides = load_lua(os.path.join(wiki, 'guides.lua'))
        self.lore = load_lua(os.path.join(wiki, 'lore.lua'))
        self.quests, self.missions = {}, {}
        for kind, store in (('quests', self.quests), ('missions', self.missions)):
            for f in os.listdir(os.path.join(wiki, kind)):
                if f.endswith('.lua'):
                    log = int(f[:-4])
                    d = load_lua(os.path.join(wiki, kind, f))
                    for i, v in (d.items() if isinstance(d, dict) else enumerate(d, 1)):
                        store[(log, i)] = v
        for store in (self.quests, self.missions):
            for v in store.values():
                for k in ('n', 'label', 'client'):
                    if v.get(k):
                        v[k] = tidy(v[k])
                if v.get('sum'):
                    v['sum'], who = split_summary(tidy(v['sum']))
                    if who and not v.get('client'):
                        v['client'] = who
        self.mobs = {}
        for f in os.listdir(os.path.join(wiki, 'zones')):
            if f.endswith('.lua'):
                self.mobs.update(load_lua(os.path.join(wiki, 'zones', f)).get('mobs', {}))
        self.crafts = self.meta['crafts']
        self.qlogs = self.meta['questLogs']
        self.mlogs = self.meta['missionLogs']

    def zone(self, z):
        return self.zones.get(z, 'zone %s' % z)

    def iname(self, i):
        return self.items.get(i, {}).get('n', 'item %s' % i)


def counted(ids, pack):
    c = defaultdict(int)
    order = []
    for i in ids:
        if i not in c:
            order.append(i)
        c[i] += 1
    return ', '.join(('%d × %s' % (c[i], pack.iname(i))) if c[i] > 1 else pack.iname(i) for i in order)


def recipe_line(r, pack):
    lv = sorted(((pack.crafts[i], x) for i, x in enumerate(r['lv']) if x), key=lambda t: -t[1])
    return '%s: %s + %s' % (', '.join('%s %d' % t for t in lv), pack.iname(r['cr']), counted(r['ing'], pack))


